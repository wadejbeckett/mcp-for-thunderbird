# third-party-licenses.sh [--check]
#
# Writes THIRD_PARTY_LICENSES at the repository root: the licence of the Go
# toolchain (its standard library and runtime are linked into the host) and
# of every Go module linked into the host binary on Linux, macOS or Windows,
# each with its version and the full text of every licence and notice file
# at its root (LICENSE*, LICENCE*, COPYING*, NOTICE*). A module that
# host/go.mod replaces is listed with its replacement ("path version =>
# replacement") and its licences are read from the replacement's directory,
# local paths included. The Apache-2.0, MIT and BSD licences of those
# modules require their notices to travel with binary copies, so every host
# package (archives, .deb, .mcpb, Windows installer, macOS pkg) ships this
# file next to LICENSE and NOTICE.
#
# A module under a copyleft licence (GPL, LGPL, AGPL, SSPL) could not be
# linked into an MPL-2.0 program distributed this way: the script fails
# when any licence text it gathers is one of those, so such a module cannot
# slip in through a dependency update.
#
# Run it after changing host/go.mod and commit the result. With --check it
# writes nothing and exits 1 when the tracked file differs from a fresh one;
# packaging/build.sh and the test workflow run that check.
# packaging/third-party-licenses-selftest.sh proves replaced modules and
# modules with several licence files are handled; it points the script at
# its own module with MFT_LICENSES_MODULE (default host/) and
# MFT_LICENSES_OUT (default THIRD_PARTY_LICENSES).
# Needs sh, go (the pinned toolchain downloads itself), find, sort and cmp.
set -eu

root=$(cd "$(dirname "$0")/.." && pwd)
out="${MFT_LICENSES_OUT:-$root/THIRD_PARTY_LICENSES}"
export GOTOOLCHAIN="${MFT_GOTOOLCHAIN:-go1.26.10}"
cd "${MFT_LICENSES_MODULE:-$root/host}"

tmp=$(mktemp)
mods="$tmp.mods"
files="$tmp.files"
trap 'rm -f "$tmp" "$mods" "$files"' EXIT

# One line per linked module other than the main one, fields separated by
# "|": path, version, the replacement if any, and last the directory go
# builds it from (the replacement's when go.mod replaces it, so a local
# path works too). Module paths cannot hold "|"; the directory comes last
# so read gives it whole.
for os in linux darwin windows; do
  GOOS=$os go list -deps -f '{{with .Module}}{{if not .Main}}{{.Path}}|{{.Version}}|{{with .Replace}}{{.Path}}{{with .Version}} {{.}}{{end}}{{end}}|{{.Dir}}{{end}}{{end}}' ./cmd/mcp-for-thunderbird
done | awk -F '|' 'NF >= 4' | sort -u >"$mods"
[ -s "$mods" ] || { echo "third-party-licenses: no modules found" >&2; exit 1; }

rule="======================================================================"
{
  echo "Third-party licences for MCP for Thunderbird"
  echo
  echo "The host program is written in Go. It statically links the Go standard"
  echo "library and runtime and the Go modules listed below. Their licences"
  echo "follow in full, as those licences require for binary distributions."
  echo "MCP for Thunderbird itself is licensed under the Mozilla Public License"
  echo "2.0 (LICENSE); material adapted from thunderbird-cli is listed in NOTICE."
  echo "This file is generated by packaging/third-party-licenses.sh from host/go.mod."
  echo
  echo "$rule"
  echo "Go standard library and runtime (https://go.dev)"
  echo "$rule"
  echo
  cat "$(go env GOROOT)/LICENSE"
  while IFS='|' read -r path version replace dir; do
    name="$path $version"
    [ -z "$replace" ] || name="$name => $replace"
    [ -n "$dir" ] && [ -d "$dir" ] || { echo "third-party-licenses: no module directory for $name" >&2; exit 1; }
    find "$dir" -maxdepth 1 -type f \( -iname 'LICENSE*' -o -iname 'LICENCE*' -o -iname 'COPYING*' -o -iname 'NOTICE*' \) | LC_ALL=C sort >"$files"
    [ -s "$files" ] || { echo "third-party-licenses: no licence file in $name ($dir)" >&2; exit 1; }
    count=$(wc -l <"$files")
    echo
    echo "$rule"
    echo "$name"
    echo "$rule"
    first=1
    while IFS= read -r licence; do
      echo
      if [ "$count" -gt 1 ]; then
        [ "$first" = 1 ] || echo
        echo "--- ${licence##*/} ---"
        echo
      fi
      first=0
      cat "$licence"
    done <"$files"
  done <"$mods"
} >"$tmp"

# The titles of the copyleft licences, as their licence files carry them.
# The MPL-2.0 text names the GNU licences in mixed case (its definition of
# a Secondary License), so only the upper-case titles count.
copyleft='^[[:space:]]*(GNU (LESSER |LIBRARY |AFFERO )?GENERAL PUBLIC LICENSE|Server Side Public License)'
if grep -qE "$copyleft" "$tmp"; then
  echo "third-party-licenses: a linked module is under a copyleft licence, which MCP for Thunderbird cannot ship:" >&2
  grep -nE "$copyleft" "$tmp" | head -n 5 >&2
  exit 1
fi

if [ "${1:-}" = "--check" ]; then
  if cmp -s "$tmp" "$out"; then
    echo "third-party-licenses: THIRD_PARTY_LICENSES is current"
  else
    echo "third-party-licenses: THIRD_PARTY_LICENSES is out of date; run sh packaging/third-party-licenses.sh and commit it" >&2
    exit 1
  fi
else
  cp "$tmp" "$out"
  chmod 0644 "$out"
  echo "$out"
fi
